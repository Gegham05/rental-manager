export function translateText(value: string, language: AppLanguage): string {
  return translations[language][value] ?? value
}

export function translateMessage(
  value: string,
  language: AppLanguage,
): string {
  const dictionary = translations[language]
  if (!dictionary) {
    return value
  }

  let translated = value
  for (const [source, target] of Object.entries(dictionary).sort(
    ([left], [right]) => right.length - left.length,
  )) {
    translated = translated.replaceAll(source, target)
  }
  return translated
}

export function getLanguageLocale(language: AppLanguage): string {
  switch (language) {
    case 'hy':
      return 'hy-AM'
    case 'en':
      return 'en-US'
    case 'ru':
      return 'ru-RU'
  }
}

export function formatGuestCapacity(count: number, language: AppLanguage): string {
  switch (language) {
    case 'hy':
      return `Մինչև ${count} հյուր`
    case 'en':
      return `Up to ${count} ${new Intl.PluralRules('en-US').select(count) === 'one' ? 'guest' : 'guests'}`
    case 'ru':
      return `До ${count} ${new Intl.PluralRules('ru-RU').select(count) === 'one' ? 'гостя' : 'гостей'}`
  }
}

export function formatStayDuration(nights: number, language: AppLanguage): string {
  switch (language) {
    case 'hy':
      return `${nights} գիշեր`
    case 'en':
      return `for ${nights} ${new Intl.PluralRules('en-US').select(nights) === 'one' ? 'night' : 'nights'}`
    case 'ru': {
      const plural = new Intl.PluralRules('ru-RU').select(nights)
      const unit = plural === 'one' ? 'ночь' : plural === 'few' ? 'ночи' : 'ночей'
      return `за ${nights} ${unit}`
    }
  }
}
